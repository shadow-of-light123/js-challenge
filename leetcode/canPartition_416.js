/**
 * 416. 分割等和子集
 * https://leetcode.cn/problems/partition-equal-subset-sum/
 *
 * 题目：给你一个只包含正整数的非空数组 nums。请你判断是否可以将这个数组
 * 分割成两个子集，使得两个子集的元素和相等。
 *
 * 核心洞察：
 *   设总和为 sum。若存在一个子集和为 sum/2，那么剩下的元素和自动也是 sum/2。
 *   所以问题等价于：从 nums 中挑若干元素（每个最多挑一次），能否凑出 sum/2。
 *   —— 这正是 0/1 背包：元素是物品，重量等于它的值，容量 target = sum/2，问能否恰好装满。
 *
 * 注意：416 要求的是「任意子集」的划分，不是「连续子数组」。
 *   例如 [3,3,6,8,16,16,16,18,20] 的合法划分是 [3,16,16,18] | [3,3,6,8,16,20]，
 *   左侧元素在原数组中并不连续，因此任何只能枚举连续区间的写法都会返回错误的 false。
 */

// ============================================================================
// 一、标准解法：一维滚动数组（0/1 背包）
// ============================================================================

/**
 * @param {number[]} nums
 * @return {boolean}
 */
var canPartition = function (nums) {
  let sum = 0;
  for (const num of nums) sum += num;
  if (sum % 2 !== 0) return false; // 和为奇数不可能平分

  const target = sum / 2;
  // dp[j] = 能否从「已经处理过的元素」中选出和为 j 的子集
  const dp = new Array(target + 1).fill(false);
  dp[0] = true; // 和为 0 永远可以做到：一个都不选（空集）

  for (const num of nums) {
    // 必须倒序，保证每个元素只用一次（0/1 背包）
    for (let j = target; j >= num; j--) {
      dp[j] = dp[j] || dp[j - num];
    }
  }

  return dp[target];
};

// ============================================================================
// 二、优化版：提前退出 + 跳过超容量元素
// ============================================================================

/**
 * @param {number[]} nums
 * @return {boolean}
 */
var canPartitionOptimized = function (nums) {
  let sum = 0;
  for (const num of nums) sum += num;
  if (sum % 2 !== 0) return false;

  const target = sum / 2;
  const dp = new Array(target + 1).fill(false);
  dp[0] = true;

  for (const num of nums) {
    if (num > target) continue; // 单个元素超过容量，必然不能选
    for (let j = target; j >= num; j--) {
      dp[j] = dp[j] || dp[j - num];
    }
    // dp 只增不减，本轮结束后目标可达即可返回（放在内层循环外，语义最清楚）
    if (dp[target]) return true;
  }

  return dp[target];
};

// ============================================================================
// 三、逐行解释
// ============================================================================
//
// ── 1. 先判奇偶 ──────────────────────────────────────────────────────────
//
//   let sum = 0;
//   for (const num of nums) sum += num;
//   if (sum % 2 !== 0) return false;
//
//   因为两个相等的整数和必定是偶数（x + x = 2x）。
//   不做这步也能靠 DP 跑出 false，但省时间。
//
// ── 2. 背包容量 ──────────────────────────────────────────────────────────
//
//   const target = sum / 2;
//
//   注意不是 sum —— 这是最容易和「子集和等于某个值」类题目混淆的地方。
//
// ── 3. dp 数组的初始化 ───────────────────────────────────────────────────
//
//   const dp = new Array(target + 1).fill(false);
//   dp[0] = true;
//
//   · 长度 target + 1：下标要从 0 取到 target（闭区间，所以 +1）
//   · .fill(false) 不能省：new Array(n) 造的是空洞数组（每个位置是 empty），
//     .fill 把它们真正填成 false
//   · dp[0] = true 是初态：和为 0 永远可以做到 —— 一个都不选（空集）。
//     这是所有背包 DP 的基准，后面 dp[num] = dp[num] || dp[0] 能变成 true 全靠它
//
// ── 4. 外层循环 ──────────────────────────────────────────────────────────
//
//   for (const num of nums) {
//
//   一件一件地把元素「放进考虑范围」。
//   每轮结束后，dp 的含义更新为「前 i 个元素能凑出哪些和」。
//
// ── 5. 内层循环边界 ──────────────────────────────────────────────────────
//
//   for (let j = target; j >= num; j--) {
//
//   · 上界 target：超过容量没意义（只关心能不能恰好到目标）
//   · 下界 num：因为要读 dp[j - num]，必须保证 j - num >= 0。
//     写成 j >= 0 + if (j >= num) 也对，j >= num 是更干净的写法，
//     也不会因为负下标得到 undefined 这类隐式 falsy 值而掩盖错误
//   · 必须从大到小：见下面第五节
//
// ── 6. 状态转移 ──────────────────────────────────────────────────────────
//
//   dp[j] = dp[j] || dp[j - num];
//
//   ... 详见第四节
//
// ── 7. 返回 ──────────────────────────────────────────────────────────────
//
//   return dp[target];
//
//   全部元素处理完后，dp[target] 就是「用整个数组能否凑出 sum/2」。

// ============================================================================
// 四、状态转移方程：它到底在说什么
// ============================================================================
//
// 一维写法里 dp[j] 的完整含义：
//
//     「处理完当前这个元素之后」，从「已经看过的元素」里挑，
//     能不能凑出和为 j 的子集。
//
// 「处理完当前元素」这几个字是理解一切的钥匙 —— 同一句话在不同循环阶段
// 指代不同的元素集合。这也是它能用一维数组原地滚动而不出错的根源。
//
// ── 读法 A：决策树（从「我」出发）────────────────────────────────────────
//
//   面对当前元素 num，想把和凑成 j，只有两种决策：
//
//     ┌──────────┬──────────────────────────────────┬──────────────────┐
//     │   决策   │              前提                │      表达        │
//     ├──────────┼──────────────────────────────────┼──────────────────┤
//     │ 不要 num │ 之前看过的元素自己就能凑出 j     │ dp[j]            │
//     │ 要 num   │ 之前看过的元素能凑出 j - num     │ dp[j - num]      │
//     └──────────┴──────────────────────────────────┴──────────────────┘
//
//   两种决策是「或」关系，任一成立即 true，所以用 ||。
//
//   注意 dp[j] 出现在等式右边，代表的是上一轮的旧值，不是新值 ——
//   这一句是全篇最容易看漏的地方，详见第五节。
//
// ── 读法 B：集合视角（从「和」出发）──────────────────────────────────────
//
//   把 dp 里 true 的下标看成集合 S = {可凑出的和}。处理 num 相当于：
//
//       S ← S ∪ (S + num)      // 把整个集合平移 num 再并回自己
//
//   即：原来能凑出的和都还能凑出（不选），同时把这些和都加上 num，
//   得到一批新的可凑出的和（选）。
//
//   这个视角很实用 —— 如果哪天要问「有哪些方案」或「最少几个元素」，
//   思路都是从这棵树分叉出去的。

// ============================================================================
// 五、为什么内层必须倒序（最关键的一节）
// ============================================================================
//
// ── 1. 先写清楚标准二维背包 ──────────────────────────────────────────────
//
//   // dp[i][j] = 只考虑前 i 个元素，能否凑出和 j
//   dp[0][0] = true;
//   dp[0][j] = false;              // j > 0
//
//   for (let i = 1; i <= n; i++) {
//     const num = nums[i - 1];
//     for (let j = 0; j <= target; j++) {
//       dp[i][j] = dp[i - 1][j]                        // 不选 num
//               || (j >= num && dp[i - 1][j - num]);   // 选 num
//     }
//   }
//   return dp[n][target];
//
//   等号右边全部是 dp[i - 1]（上一行），绝不会出现 dp[i][...] 本身。
//   这就是「每个元素最多用一次」在公式层面的保证 ——
//   决策只能建立在「这个元素还没进场」的状态上。
//
// ── 2. 维度压缩 ──────────────────────────────────────────────────────────
//
//   第 i 行只依赖第 i - 1 行；更细一点，dp[i][j] 只依赖 dp[i-1][j]
//   和 dp[i-1][j-num]，全都是同列或左边的列。所以：
//     · 不需要保存整个表格，只要一行
//     · 只要保证在覆盖 dp[j-num] 之前先读到它的旧值
//
//   一维版本中 dp[j] 的物理含义随执行阶段变化：
//
//     ┌────────────────────────────────────┬────────────────┐
//     │               时刻                 │ dp[j] 指代的行 │
//     ├────────────────────────────────────┼────────────────┤
//     │ 第 i 轮内层循环开始前              │ 第 i-1 行      │
//     │ 第 i 轮中、刚刚写过 dp[j]          │ 第 i 行        │
//     │ 第 i 轮中、还没轮到 dp[j]          │ 仍是第 i-1 行  │
//     └────────────────────────────────────┴────────────────┘
//
//   倒序的威力：遍历到 j 时，j - num < j，而 j-num 位于尚未处理的区间，
//   仍然停留在第 i - 1 行 —— 读到的正是上一行。语义完全等价于二维公式。
//
// ── 3. 正序为什么错（用最小反例看清）────────────────────────────────────
//
//   正序时，j - num < j 已经在本轮被走过一次，里面混入了 num 本身。
//   这相当于把二维公式里的 dp[i-1][j-num] 偷换成了 dp[i][j-num] ——
//   同一个元素被用了两次。
//
//   玩具例子：nums = [2]，target = 6（假设上下文需要凑 6）
//
//     初态:     dp = [T, ., ., ., ., ., .]      下标 0..6
//
//     正序(j=2→6):
//       j=2: dp[2] = dp[2] || dp[0]  → T     (用了 1 个 2)
//       j=4: dp[4] = dp[4] || dp[2]  → T     ← 这里的 dp[2] 是本轮刚写的，等于又用了一个 2
//       j=6: dp[6] = dp[6] || dp[4]  → T     ← 三次 ❌
//     结果 dp[6] = true —— 但数组里只有一个 2，凑不出 6
//
//     倒序(j=6→2):
//       j=6: dp[6] = dp[6] || dp[4]  → F     ← dp[4] 还是旧值 false
//       j=4: dp[4] = dp[4] || dp[2]  → F     ← dp[2] 还是旧值 false
//       j=2: dp[2] = dp[2] || dp[0]  → T
//     结果 dp[6] = false ✓
//
//   再看稍微完整一点的 nums = [2,3,5] 在正确版本里两个方向的表现：
//
//     初态          T . . . . .        (j: 0 1 2 3 4 5)
//
//     倒序（正确）
//       处理 2 后   T . T . . .
//       处理 3 后   T . T T . T
//       处理 5 后   T . T T . T
//       最终        T . T T . T        dp[5]=T ✓（= 5 本身）
//                     ↑     ↑
//                   dp[1]、dp[4] 为 F —— 集合 {2,3,5} 确实凑不出 1 和 4 ✓
//
//     正序（错误）
//       处理 2 后   T . T . T .        ← dp[4] 已经是 T，只用 {2} 却凑出了 4（2+2）❌
//       处理 3 后   T . T T T T
//       处理 5 后   T . T T T T        dp[4] 依然虚高
//
//   dp[4] 这个多出来的 true 就是「元素被重复使用」的痕迹。在 416 里它不一定
//   恰好让最终答案翻错（取决于 target），但逻辑已经崩了 —— 换个数据就会踩雷。
//
//   口诀：倒序 = 0/1（每件一次），正序 = 完全背包（每件无限次）。
//         两者共享同一行转移式，差别只在遍历方向。

// ============================================================================
// 六、把 dp[j] 放在 || 左边的两个理由
// ============================================================================
//
//   dp[j] = dp[j] || dp[j - num];
//
//   1. 语义必需：不选当前元素也是一条合法路径，所以旧值 dp[j] 必须参与「或」。
//      如果写成 dp[j] = dp[j - num]，就变成「每个和都必须包含当前元素」，显然错。
//
//   2. 工程顺手：|| 是短路求值。一旦 dp[j] 已经是 true，右边的 dp[j-num]
//      根本不会被求值 —— 省一次数组读取。
//      等价写法 dp[j] ||= dp[j - num]（ES2021 逻辑赋值）更加直白。
//
//   也正因为 dp 只存布尔值，这里用 || 而不是 +：
//   我们问的是「可不可行」，不是「有多少种方案」。
//   若题目改成「有多少种划分方式」，转移式就得换成 dp[j] += dp[j - num]
//   （且倒序依然是为了每件一次），dp 的类型也要从 boolean 变成计数。

// ============================================================================
// 七、方程与题目要求的对应关系
// ============================================================================
//
//   ┌─────────────────────────────┬──────────────────────────────────────┐
//   │        416 题的语言         │              DP 的语言               │
//   ├─────────────────────────────┼──────────────────────────────────────┤
//   │ 每个数只能用一次            │ 0/1 背包，所以内层倒序               │
//   │ 选一些数让和等于 sum/2      │ 容量 target = sum/2，可达性 DP       │
//   │ 剩下的数自动和为 sum/2      │ 无需额外判断，补集自动成立           │
//   │ 返回 boolean                │ dp 存布尔，转移用 ||                 │
//   └─────────────────────────────┴──────────────────────────────────────┘

// ============================================================================
// 八、代码之外的第一个问题：原写法为什么过不了
// ============================================================================
//
// 之前用双重循环枚举「连续子数组」：
//
//   for (let i = 0; i < nums.length; i++) {
//     let now = 0;
//     for (let j = i; j < nums.length; j++) {
//       now += nums[j];
//       if (now === sum - now) return true;
//     }
//   }
//
// 只能检查 nums[i..j] 这种连续区间的和，永远拼不出像 [3,16,16,18] 这样
// 跳过中间元素的组合。416 要的是「子集」，不是「子数组」。
//
//   样例 [1,5,11,5] → [11] | [1,5,5]，两段刚好各自连续，碰巧能过
//   样例 [1,2,3,5]  → 总和 11 为奇数，直接 false
//   样例 [3,3,6,8,16,16,16,18,20] → 总和 106，一半 53，
//                                   唯一可行子集 [3,16,16,18] 不连续 → 必挂
//
// 如果一定要用连续子数组的思路，那只能解决「最大子数组和」这类题；
// 416 的「子集」性质决定了必须用背包 / DFS / 位运算枚举组合，没有捷径。

// ============================================================================
// 九、复杂度
// ============================================================================
//
//   时间 O(n × target)：n ≤ 200、target ≤ 10000，约 2×10^6 次，轻松通过
//   空间 O(target)：只有一维数组

// ============================================================================
// 十、彩蛋：BigInt 位运算写法
// ============================================================================
//
//   let bits = 1n;
//   for (const num of nums) bits |= bits << BigInt(num);
//   return ((bits >> BigInt(target)) & 1n) === 1n;
//
//   本质和滚动数组完全一样（bits 的第 j 位就对应 dp[j]），
//   只是把数组并行化进了二进制位里。
//   理解了滚动数组再看这个会很顺，但注意 JS 的 << 只对 BigInt 支持任意位数，
//   普通 number 是 32 位的，会溢出。

var canPartitionBitset = function (nums) {
  let sum = 0;
  for (const num of nums) sum += num;
  if (sum % 2 !== 0) return false;
  const target = sum / 2;

  let bits = 1n;
  for (const num of nums) bits |= bits << BigInt(num);
  return ((bits >> BigInt(target)) & 1n) === 1n;
};

// ============================================================================
// 测试
// ============================================================================

const canPartition2D = function (nums) {
  let sum = 0;
  for (const num of nums) sum += num;
  if (sum % 2 !== 0) return false;
  const target = sum / 2;
  const n = nums.length;

  // dp[i][j] = 只考虑前 i 个元素，能否凑出和 j
  const dp = Array.from({ length: n + 1 }, () => new Array(target + 1).fill(false));
  for (let i = 0; i <= n; i++) dp[i][0] = true;

  for (let i = 1; i <= n; i++) {
    const num = nums[i - 1];
    for (let j = 0; j <= target; j++) {
      dp[i][j] = dp[i - 1][j] || (j >= num && dp[i - 1][j - num]);
    }
  }
  return dp[n][target];
};

/** 暴力枚举所有子集，用于对拍 */
const bruteForce = function (nums) {
  const sum = nums.reduce((a, b) => a + b, 0);
  if (sum % 2 !== 0) return false;
  const target = sum / 2;
  const n = nums.length;
  for (let mask = 0; mask < 1 << n; mask++) {
    let s = 0;
    for (let i = 0; i < n; i++) if (mask & (1 << i)) s += nums[i];
    if (s === target) return true;
  }
  return false;
};

const cases = [
  // [输入, 期望]
  [[1, 5, 11, 5], true],
  [[1, 2, 3, 5], false],
  [[3, 3, 6, 8, 16, 16, 16, 18, 20], true], // 本题样例：原写法在此挂掉
  [[1], false],
  [[2], false],
  [[1, 1], true],
  [[2, 2, 3, 5], false],
  [[1, 2, 5], false],
  [[2, 3, 5], true],
  [[1, 1, 1], false],
];

const solutions = [
  ['canPartition (1D)', canPartition],
  ['canPartitionOptimized', canPartitionOptimized],
  ['canPartition2D', canPartition2D],
  ['canPartitionBitset', canPartitionBitset],
  ['bruteForce', bruteForce],
];

let failed = 0;
for (const [name, fn] of solutions) {
  for (const [nums, expected] of cases) {
    const actual = fn([...nums]);
    const ok = actual === expected;
    if (!ok) failed++;
    console.log(
      `${ok ? '✓' : '✗'} ${name.padEnd(22)} ${JSON.stringify(nums).padEnd(34)} => ${
        ok ? actual : `${actual} (期望 ${expected})`
      }`
    );
  }
}
console.log(failed === 0 ? '\n全部通过' : `\n${failed} 个用例失败`);
